import type { Pool } from 'pg';
import { EMBEDDING_DIMENSION, type EmbeddingPort } from '@vaarg/shared';
import { scopedCatalogTransaction } from '../commerce/scope.js';

/**
 * FL05 TASK 06 — incremental embedding job handler. Selects visible search
 * documents whose stored embedding is missing or stale (content_hash
 * mismatch) for the configured model identity, embeds them OUTSIDE any
 * database transaction (provider calls never hold a transaction open), then
 * upserts with stale-embedding rejection: the content_hash observed when
 * the batch was read is re-checked inside the write transaction — if the
 * document changed mid-flight, the row is skipped and picked up by the next
 * run, so a stale embedding is never written over fresh content (nor fresh
 * content marked as embedded).
 *
 * Prepared for FL06 Hatchet execution: `runEmbeddingJob` is a plain,
 * cancellation-aware function with bounded work; the durable workflow runner
 * will simply invoke it. This module does NOT create another workflow engine.
 */

export interface EmbeddingJobScope {
  storeId: string;
  country: string;
  language: string;
}

export interface EmbeddingJobOptions {
  /** Bounded batch of documents per run (default 64, max 256). */
  batchSize?: number;
  /** Stop after this many documents (bounded run). */
  maxDocuments?: number;
  signal?: AbortSignal;
}

export interface EmbeddingJobResult {
  status: 'COMPLETED' | 'NOT_CONFIGURED' | 'PARTIAL';
  processed: number;
  embedded: number;
  skipped: number;
  stale: number;
  remaining: number;
}

interface PendingRow {
  product_gid: string;
  title_normalized: string;
  body_normalized: string;
  tags_normalized: string[];
  content_hash: string;
  generation: string;
}

interface CurrentRow {
  product_gid: string;
  content_hash: string;
  generation: string;
}

function documentText(row: PendingRow): string {
  return [row.title_normalized, row.body_normalized, row.tags_normalized.join(' ')]
    .filter((part) => part.length > 0)
    .join(' ');
}

/**
 * One incremental embedding run. Returns explicit NOT_CONFIGURED status when
 * the provider is unavailable — vectors are NEVER generated by any other
 * means (no random fallback, no zeros).
 */
export async function runEmbeddingJob(
  pool: Pool,
  embedding: EmbeddingPort,
  scope: EmbeddingJobScope,
  options: EmbeddingJobOptions = {},
): Promise<EmbeddingJobResult> {
  const identity = embedding.identity();
  if (embedding.availability() !== 'READY' || !identity) {
    return { status: 'NOT_CONFIGURED', processed: 0, embedded: 0, skipped: 0, stale: 0, remaining: 0 };
  }
  if (identity.dimension !== EMBEDDING_DIMENSION) {
    throw new Error('EMBEDDING_DIMENSION_MISMATCH');
  }
  const batchSize = Math.min(Math.max(options.batchSize ?? 64, 1), 256);
  const maxDocuments = Math.min(Math.max(options.maxDocuments ?? 256, 1), 1024);
  if (options.signal?.aborted) throw new Error('ABORTED');

  // Phase 1 (read, short transaction): pending documents for this model.
  const pending = await scopedCatalogTransaction(pool, scope, async (client) => {
    const result = await client.query<PendingRow>(
      `SELECT sd.product_gid, sd.title_normalized, sd.body_normalized, sd.tags_normalized, sd.content_hash, sd.generation
       FROM catalog_search_documents sd
       WHERE sd.store_id=$1 AND sd.country=$2 AND sd.language=$3 AND sd.visible=true
         AND NOT EXISTS (
           SELECT 1 FROM catalog_product_embeddings e
           WHERE e.store_id=sd.store_id AND e.country=sd.country AND e.language=sd.language
             AND e.product_gid=sd.product_gid
             AND e.model=$4 AND e.model_version=$5 AND e.dimension=$6
             AND e.content_hash=sd.content_hash AND e.generation=sd.generation AND e.provider=$8
         )
       ORDER BY sd.product_gid
       LIMIT $7`,
      [
        scope.storeId,
        scope.country,
        scope.language,
        identity.model,
        identity.modelVersion,
        identity.dimension,
        Math.min(batchSize, maxDocuments),
        identity.provider,
      ],
    );
    return result.rows;
  });
  if (options.signal?.aborted) throw new Error('ABORTED');
  if (pending.length === 0) {
    return { status: 'COMPLETED', processed: 0, embedded: 0, skipped: 0, stale: 0, remaining: 0 };
  }

  // Phase 2 (provider): OUTSIDE any database transaction.
  let embeddedBatch;
  try {
    embeddedBatch = await embedding.embedDocuments(
      pending.map(documentText),
      options.signal ? { signal: options.signal } : {},
    );
  } catch (error) {
    if (options.signal?.aborted || (error instanceof Error && error.message === 'ABORTED')) {
      throw error;
    }
    return {
      status: 'PARTIAL',
      processed: 0,
      embedded: 0,
      skipped: pending.length,
      stale: 0,
      remaining: pending.length,
    };
  }
  if (
    embeddedBatch.identity.provider !== identity.provider ||
    embeddedBatch.identity.model !== identity.model ||
    embeddedBatch.identity.modelVersion !== identity.modelVersion ||
    embeddedBatch.identity.dimension !== identity.dimension
  ) {
    throw new Error('EMBEDDING_IDENTITY_MISMATCH');
  }
  if (embeddedBatch.vectors.length !== pending.length) {
    throw new Error('EMBEDDING_INVALID_RESPONSE');
  }
  if (options.signal?.aborted) throw new Error('ABORTED');

  // Phase 3 (write): guarded upsert with stale rejection. The content_hash
  // captured at phase 1 is compared against the CURRENT hash inside the
  // write transaction; changed documents are skipped (next run re-embeds).
  const written = await scopedCatalogTransaction(pool, scope, async (client) => {
    const current = await client.query<CurrentRow>(
      `SELECT product_gid, content_hash, generation FROM catalog_search_documents
       WHERE store_id=$1 AND country=$2 AND language=$3 AND product_gid = ANY($4::text[]) AND visible=true FOR UPDATE`,
      [scope.storeId, scope.country, scope.language, pending.map((row) => row.product_gid)],
    );
    const currentDocs = new Map(current.rows.map((row) => [row.product_gid, row]));

    let embedded = 0;
    let stale = 0;
    for (let index = 0; index < pending.length; index += 1) {
      const row = pending[index];
      const vector = embeddedBatch.vectors[index];
      if (!row || !vector) continue;
      if (vector.length !== identity.dimension || vector.some(value => !Number.isFinite(value))) throw new Error('EMBEDDING_INVALID_RESPONSE');
      const document = currentDocs.get(row.product_gid);
      const observedHash = document?.content_hash;
      // Stale embedding rejection: document changed after we embedded it.
      if (observedHash !== row.content_hash || document?.generation !== row.generation) {
        stale += 1;
        continue;
      }
      const result = await client.query(
        `INSERT INTO catalog_product_embeddings
           (store_id, country, language, product_gid, model, model_version, dimension, content_hash, embedding, generation, provider)
         VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9::vector, $10, $11)
         ON CONFLICT (store_id, country, language, product_gid, provider, model, model_version)
         DO UPDATE SET
           embedding = EXCLUDED.embedding,
           content_hash = EXCLUDED.content_hash,
           generation = EXCLUDED.generation,
           updated_at = now()
         WHERE catalog_product_embeddings.content_hash IS DISTINCT FROM EXCLUDED.content_hash
            OR catalog_product_embeddings.generation IS DISTINCT FROM EXCLUDED.generation
            OR catalog_product_embeddings.embedding IS DISTINCT FROM EXCLUDED.embedding`,
        [
          scope.storeId,
          scope.country,
          scope.language,
          row.product_gid,
          identity.model,
          identity.modelVersion,
          identity.dimension,
          observedHash,
          `[${vector.join(',')}]`,
          document!.generation,
          identity.provider,
        ],
      );
      if ((result.rowCount ?? 0) > 0) embedded += 1;
    }
    return { embedded, stale };
  });

  const remaining = await scopedCatalogTransaction(pool, scope, async (client) => {
    const result = await client.query<{ count: string }>(
      `SELECT count(*)::text AS count
       FROM catalog_search_documents sd
       WHERE sd.store_id=$1 AND sd.country=$2 AND sd.language=$3 AND sd.visible=true
         AND NOT EXISTS (
           SELECT 1 FROM catalog_product_embeddings e
           WHERE e.store_id=sd.store_id AND e.country=sd.country AND e.language=sd.language
             AND e.product_gid=sd.product_gid
             AND e.model=$4 AND e.model_version=$5 AND e.dimension=$6
             AND e.content_hash=sd.content_hash AND e.generation=sd.generation AND e.provider=$7
         )`,
      [scope.storeId, scope.country, scope.language, identity.model, identity.modelVersion, identity.dimension, identity.provider],
    );
    return Number(result.rows[0]?.count ?? '0');
  });

  return {
    status: remaining > 0 ? 'PARTIAL' : 'COMPLETED',
    processed: pending.length,
    embedded: written.embedded,
    skipped: embeddedBatch.vectors.length - pending.length,
    stale: written.stale,
    remaining,
  };
}

/** Durable-workflow-shaped handler for FL06 Hatchet wiring (no engine here). */
export interface EmbeddingJobContext {
  jobId: string;
  attempt: number;
  payload: EmbeddingJobScope & { batchSize?: number; maxDocuments?: number };
  signal?: AbortSignal;
}

export function createEmbeddingJobHandler(deps: { pool: Pool; embedding: EmbeddingPort }) {
  return async function handleEmbeddingJob(context: EmbeddingJobContext): Promise<void> {
    const result = await runEmbeddingJob(
      deps.pool,
      deps.embedding,
      {
        storeId: context.payload.storeId,
        country: context.payload.country,
        language: context.payload.language,
      },
      {
        ...(context.payload.batchSize !== undefined ? { batchSize: context.payload.batchSize } : {}),
        ...(context.payload.maxDocuments !== undefined ? { maxDocuments: context.payload.maxDocuments } : {}),
        ...(context.signal ? { signal: context.signal } : {}),
      },
    );
    if (result.status === 'NOT_CONFIGURED') {
      throw new Error('EMBEDDING_NOT_CONFIGURED');
    }
  };
}
